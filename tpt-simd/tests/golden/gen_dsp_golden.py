"""Generate tests/golden/dsp_golden.rs: reference outputs from independent oracles.

Oracles (none of them is the tpt-simd code under test):
  * scipy.signal.windows  -> Hamming, Hann, Blackman, Kaiser (sym=True)
  * numpy.convolve        -> full 1-D convolution (float64)
  * numpy.matmul          -> 4x4 f32 product (float64)
  * numpy.linalg.inv      -> 3x3 inverse (float64)
  * exact integer maths   -> Q15 FIR with round-half-up and saturation

Run from anywhere:  python tpt-simd/tests/golden/gen_dsp_golden.py
Requires numpy and scipy. The output is committed; rerun only when the
inputs below change.
"""

import os

import numpy as np
from scipy.signal import windows

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "dsp_golden.rs")


def f32_literal(v):
    # Shortest decimal that round-trips through f32, so clippy's
    # excessive_precision lint has nothing to flag.
    text = np.format_float_scientific(np.float32(v), unique=True)
    text = text.replace(".e", ".0e")
    return f"{text}_f32"


def rust_f32_array(name, values):
    body = ", ".join(f32_literal(v) for v in values)
    return f"const {name}: &[f32] = &[{body}];\n"


def rust_i16_array(name, values):
    body = ", ".join(str(int(v)) for v in values)
    return f"const {name}: &[i16] = &[{body}];\n"


def rust_f32_mat(name, m):
    rows = ["    [" + ", ".join(f32_literal(v) for v in row) + "]," for row in m]
    return f"const {name}: [[f32; {len(m[0])}]; {len(m)}] = [\n" + "\n".join(rows) + "\n];\n"


def main():
    out = []
    out.append(
        "// Golden outputs generated by `tests/golden/gen_dsp_golden.py`.\n"
        "// Do not edit by hand: rerun the generator instead.\n"
        "//\n"
        "// Each expected value comes from an independent oracle (scipy, numpy,\n"
        "// or exact integer arithmetic), not from the crates' own scalar paths.\n"
        "// Included by tests/dsp_conformance.rs.\n\n"
    )

    # --- Windows (scipy.signal.windows, symmetric form) -------------------
    # Tolerances: the cosine-sum windows are accurate to ~3e-6 (crate docs),
    # Kaiser is computed in f64 and rounded to f32.
    sizes = [1, 2, 3, 8, 17, 64]
    for n in sizes:
        out.append(rust_f32_array(f"HAMMING_{n}", windows.hamming(n, sym=True)))
        out.append(rust_f32_array(f"HANN_{n}", windows.hann(n, sym=True)))
        out.append(rust_f32_array(f"BLACKMAN_{n}", windows.blackman(n, sym=True)))
        out.append(rust_f32_array(f"KAISER8_{n}", windows.kaiser(n, 8.0, sym=True)))
    out.append("\n")

    # --- Full 1-D convolution (numpy, float64) ----------------------------
    x = np.array([np.sin(0.37 * i) + 0.5 * np.cos(1.1 * i) for i in range(37)])
    k = np.array([0.25, -0.5, 1.0, 0.75, -0.125, 0.0625, 0.3, -0.9, 0.42])
    out.append(rust_f32_array("CONV_INPUT", x))
    out.append(rust_f32_array("CONV_KERNEL", k))
    out.append(rust_f32_array("CONV_EXPECTED", np.convolve(x, k, mode="full")))
    out.append("\n")

    # --- 4x4 product and 3x3 inverse --------------------------------------
    a4 = np.array([[(r * 4 + c) * 0.1 - 0.7 for c in range(4)] for r in range(4)])
    b4 = np.array([[np.cos(0.9 * r + 0.4 * c) for c in range(4)] for r in range(4)])
    out.append(rust_f32_mat("MAT4_A", a4))
    out.append(rust_f32_mat("MAT4_B", b4))
    out.append(rust_f32_mat("MAT4_PRODUCT", a4 @ b4))

    m3 = np.array([[4.0, 1.0, -2.0], [0.5, 3.0, 1.0], [-1.0, 0.25, 2.5]])
    out.append(rust_f32_mat("MAT3", m3))
    out.append(rust_f32_mat("MAT3_INVERSE", np.linalg.inv(m3)))
    out.append("\n")

    # --- Q15 FIR (exact integers; round half up, saturate to i16) ---------
    fir_in = [100, -2000, 32767, -32768, 12345, 555, -9000, 20000, 1, -1]
    fir_taps = [16384, 8192, -4096, 32767]
    fir_out = []
    for n in range(len(fir_in)):
        acc = 0
        for j, c in enumerate(fir_taps):
            if n - j >= 0:
                acc += c * fir_in[n - j]
        val = (acc + (1 << 14)) >> 15  # arithmetic shift: floor division
        fir_out.append(max(-32768, min(32767, val)))
    out.append(rust_i16_array("FIR_INPUT", fir_in))
    out.append(rust_i16_array("FIR_TAPS", fir_taps))
    out.append(rust_i16_array("FIR_EXPECTED", fir_out))

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(out))
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
